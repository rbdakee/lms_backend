"""ИИН — индивидуальный идентификационный номер, 12 цифр.

Хранится строкой: ведущий ноль значащий, число его съест
(CERTIFICATES_BRIEF, 1).

Заглушка стоит у всех, кто зарегистрировался до 04.09.2026, и означает
«не заполнен», а не «ИИН такой»: настоящий номер из одних нулей не бывает.
Поэтому уникальность на заглушку не распространяется, а онбординг считает
её незаполненным полем.

ИИН — персональные данные, и более чувствительные, чем всё остальное, что мы
храним: ни в лог, ни в текст ошибки он не попадает. Здесь номер только
проверяется, наружу отсюда не уходит ничего, кроме «да» и «нет».
"""

import re

IIN_PLACEHOLDER = "000000000000"
IIN_LENGTH = 12

# Ровно 12 цифр ASCII. Через регулярное выражение, а не str.isdigit(): тот
# пропускает арабские и надстрочные цифры, а в реестр академии уходит ровно
# то, что лежит в базе.
_IIN_RE = re.compile(rf"^[0-9]{{{IIN_LENGTH}}}$")


def normalize_iin(raw: str) -> str | None:
    """Возвращает 12 цифр или None, если это не ИИН.

    Контрольная цифра не проверяется (решение владельца 04.09.2026). Формула,
    по которой последняя цифра считается из первых одиннадцати, поймала бы
    опечатку, но ошибка в нашей реализации заперла бы живого человека снаружи
    собственного аккаунта — цена ошибки несимметрична.
    """
    value = raw.strip()
    if _IIN_RE.match(value) is None:
        return None
    # Вписать себе метку «не заполнен» руками нельзя: настоящего такого
    # номера не существует, а онбординг после него пустил бы человека дальше
    return None if value == IIN_PLACEHOLDER else value


def iin_filled(iin: str) -> bool:
    """Номер настоящий, а не метка «не заполнен»."""
    return bool(iin) and iin != IIN_PLACEHOLDER
