"""Бренд площадки: название, организация, контакты и картинки.

Раньше это были строки таблицы `setting`, которые правил админ на вкладке
«Бренд и контакты». С двумя площадками бренд стал разным у каждой и перестал
быть настройкой: он фиксирован и живёт в коде, а вкладка из админки убрана
целиком (PLATFORMS_BRIEF, решение 4). Меняется он правкой этого файла
и выкаткой — как шаблон сертификата, который тоже свёрстан в коде.

Картинки лежат рядом файлами, в `app/assets/brands/<код площадки>/`, а здесь
только их имена: домен описывает бренд, но байтов не отдаёт. Файла может
не быть вовсе — тогда слот пустой, и это не ошибка: `GET /branding/{slot}`
отвечает тем же 404, что и выдуманное имя слота, а на сертификате место
просто остаётся пустым.

Домена площадки здесь нет: наружу он отсюда не уходит, а адреса, которые
сервер собирает сам, живут в настройках сервиса (`PUBLIC_BASE_URL`,
`VERIFY_BASE_URL`) — они про деплой, а не про бренд.
"""

from dataclasses import dataclass

from app.domain.platform import PLATFORMS

# Логотип площадки — свой слот; три картинки сертификата шаблон зовёт короче,
# чем называется слот, и это соответствие нужно генерации PDF.
LOGO_SLOT = "logo"
CERT_SLOTS = {"logo": "cert_logo", "sign": "cert_sign", "stamp": "cert_stamp"}
SLOTS = (LOGO_SLOT, *CERT_SLOTS.values())


@dataclass(frozen=True)
class Contacts:
    """Контакты администратора площадки: их показывает подвал и кнопка
    «Связаться с администратором».

    `phone` и `whatsapp` — именно номера, а не ссылки: ссылку wa.me собирает
    фронт. Номера у площадок разные, даже если человек за ними один.
    """

    name: str
    phone: str
    whatsapp: str
    hours: str


@dataclass(frozen=True)
class Brand:
    platform_name: str
    org_name: str
    contacts: Contacts
    # Имена файлов по слотам картинок
    images: dict[str, str]

    def __post_init__(self) -> None:
        # Забытый слот молча отвечал бы 404 — тем же, что и не положенный
        # файл, — и разницу было бы видно только на выданной бумаге
        if set(self.images) != set(SLOTS):
            raise RuntimeError(f"Бренд {self.platform_name}: слоты картинок — {SLOTS}")


# Коды берутся из PLATFORMS, а не переписываются рядом: список площадок один
# на весь бэкенд, и третья площадка должна ронять сборку здесь, а не молча
# оставаться без бренда.
P1, P2 = PLATFORMS

# ЗАМЕНИТЬ ЦЕЛИКОМ. Настоящих значений в репозитории нет ни у одной площадки:
# бренд первой лежал строками `setting` в боевой базе, второй — ещё не назван
# владельцем (PLATFORMS_BRIEF, «Ждём от владельца»). Всё, что ниже, —
# плейсхолдеры; каждый помечен своей строкой «заменить».
BRANDS: dict[str, Brand] = {
    P1: Brand(
        platform_name="Площадка 1",  # заменить: название в шапке и в подвале
        org_name="Организация первой площадки",  # заменить: кто выдаёт сертификат
        contacts=Contacts(
            name="Администратор первой площадки",  # заменить: ФИО администратора
            phone="+70000000001",  # заменить: номер для звонка
            whatsapp="+70000000001",  # заменить: номер WhatsApp
            hours="Будни, 9:00–18:00",  # заменить: часы работы
        ),
        images={
            # заменить: имена файлов в app/assets/brands/p1/ — вместе
            # с расширением, если картинка не png
            LOGO_SLOT: "logo.png",
            "cert_logo": "cert_logo.png",
            "cert_sign": "cert_sign.png",
            "cert_stamp": "cert_stamp.png",
        },
    ),
    P2: Brand(
        platform_name="Площадка 2",  # заменить: название в шапке и в подвале
        org_name="Организация второй площадки",  # заменить: кто выдаёт сертификат
        contacts=Contacts(
            name="Администратор второй площадки",  # заменить: ФИО администратора
            phone="+70000000002",  # заменить: номер для звонка
            whatsapp="+70000000002",  # заменить: номер WhatsApp
            hours="Будни, 9:00–18:00",  # заменить: часы работы
        ),
        images={
            # заменить: имена файлов в app/assets/brands/p2/ — вместе
            # с расширением, если картинка не png
            LOGO_SLOT: "logo.png",
            "cert_logo": "cert_logo.png",
            "cert_sign": "cert_sign.png",
            "cert_stamp": "cert_stamp.png",
        },
    ),
}


def brand(platform: str) -> Brand:
    """Бренд площадки.

    Неизвестный код — ошибка программиста, а не запроса: площадку выбирает
    `platform_of` из `PLATFORMS`, и подставить сюда своё значение снаружи
    нельзя.
    """
    return BRANDS[platform]
