"""Файл сданной работы: как он называется в постоянной ссылке и какого он типа.

Ссылка на работу постоянная и уходит в адресную строку, поэтому имя в ней
переводится в латиницу: «Дескрипторы.docx» превращается в `deskriptory.docx`,
а не в строку процентов. Хранимое имя работы при этом остаётся исходным —
под ним файл и сохранится, имя в адресе сервер не читает вовсе.
"""

import mimetypes
import re
from pathlib import PurePosixPath

DEFAULT_MIME = "application/octet-stream"

# Русские и казахские буквы: работы приходят и на том, и на другом языке.
TRANSLIT = {
    "а": "a", "ә": "a", "б": "b", "в": "v", "г": "g", "ғ": "g", "д": "d",
    "е": "e", "ё": "e", "ж": "zh", "з": "z", "и": "i", "і": "i", "й": "i",
    "к": "k", "қ": "k", "л": "l", "м": "m", "н": "n", "ң": "n", "о": "o",
    "ө": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ұ": "u",
    "ү": "u", "ф": "f", "х": "h", "һ": "h", "ц": "c", "ч": "ch", "ш": "sh",
    "щ": "sch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def ext_of(name: str) -> str:
    """Расширение без точки и в нижнем регистре: «Работа.PDF» — тот же pdf."""
    return PurePosixPath(name).suffix.lstrip(".").lower()


def mime_of(name: str) -> str:
    """Тип по имени файла: присланному браузером верить нечего."""
    return mimetypes.guess_type(name)[0] or DEFAULT_MIME


def slug(name: str) -> str:
    """Имя файла для адреса ссылки: латиница, цифры и точка, остальное — дефис."""
    latin = "".join(TRANSLIT.get(char, char) for char in name.lower())
    cleaned = re.sub(r"[^a-z0-9.]+", "-", latin)
    # Дефис рядом с точкой — след от пробела перед расширением, он не нужен
    return re.sub(r"-*\.+-*", ".", cleaned).strip("-.") or "file"


def file_url(base_url: str, submission_id: int, index: int, name: str) -> str:
    """Постоянная ссылка на файл работы. Ключ хранилища в неё не попадает:
    наружу уходит номер сдачи и позиция файла в ней, а байты отдаются
    с проверкой сессии — автору работы и админам."""
    return f"{base_url}/files/submission/{submission_id}/{index}/{slug(name)}"
