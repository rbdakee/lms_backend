"""Русское склонение при числе.

Отдельным модулем, потому что нужно сразу в двух слоях: тексты ошибок
собираются в `domain/errors.py`, а чек-лист готовности курса — в сценарии
редактора. Обе строки админ читает целиком, на фронте они не собираются,
и «1 доступов» там видно как есть.
"""


def plural(count: int, one: str, few: str, many: str) -> str:
    """Форма слова при числе: 1 элемент, 2 элемента, 5 элементов.

    11–14 идут по `many` при любой последней цифре: «11 элементов»,
    а не «11 элемент».
    """
    if count % 10 == 1 and count % 100 != 11:
        return one
    if count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
        return few
    return many
