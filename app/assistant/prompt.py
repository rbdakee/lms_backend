"""Промпт ассистента: шесть частей, собираемых заново на каждый ход.

Порядок частей задан брифом (`ASSISTANT_BRIEF`, раздел 3) и здесь соблюдён.

Постоянное — системным сообщением (`build_system`), одно и то же у всех
чатов и всех админов:

1. кто он и с кем говорит — константа;
2. выжимка о продукте — `knowledge.py`;
3. правила разговора и работы с инструментами — константа;
4. список инструментов — из реестра.

Меняющееся — отдельным сообщением сразу за ним (`build_state`):

5. индекс памяти — `assistant_memory`;
6. состояние: дата, закреплённый курс, действующие допуски — из базы.

**Разделены они ради счёта, а не ради красоты.** Провайдер считает совпадающее
начало запроса вчетверо дешевле и бьёт кэш на первом расхождении. Закреплённый
курс и допуски свои у каждого чата: пока они стояли внутри системного
сообщения, из общего кэша выпадал и реестр — а это почти весь вход запроса,
и каждый новый чат оплачивал его по полной цене. Замерено 10.09.2026 на живых
запросах: новый чат получает из кэша **98%** — против 13%, когда меняющееся
стоит в хвосте того же сообщения, и против нуля, когда оно стоит в середине.
Модель при этом видит ровно тот же текст, что и раньше.

**Дата обязательна.** У курсов есть сроки, у заявки — «ждёт 4 дня»,
у сертификата — дата выдачи. Без сегодняшней даты модель отсчитывает их
от даты своего обучения и уверенно называет неверные числа.

Персданных в промпте нет ни одного — включая примеры. Ключей и адресов тоже.
"""

from datetime import datetime

from app.assistant.knowledge import KNOWLEDGE
from app.assistant.registry import ToolSpec
from app.domain.brands import brand
from app.domain.kz_time import ALMATY
from app.domain.platform import PLATFORMS

# Как ассистент себя называет. Рабочее слово — имя за владельцем
# (`ASSISTANT_BRIEF`, раздел 14), поэтому оно здесь одной константой.
ASSISTANT_NAME = "Ассистент"

MONTHS = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)
WEEKDAYS = ("понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье")


WHO = f"""\
Ты — {ASSISTANT_NAME.lower()} администратора платформы курсов повышения
квалификации для учителей Казахстана. Ты работаешь **внутри админки**
и говоришь с сотрудником, а не с учителем.

Ты делаешь работу админа через закрытый список действий — инструментов.
Своего кода ты не трогаешь, в базу мимо инструментов не ходишь и не умеешь
ничего, чего не умеет админ руками.\
"""


RULES = """\
## Как ты разговариваешь

- По-русски, коротко, по делу. Без «Конечно!», без «Отличный вопрос»,
  без пересказа того, что админ только что написал.
- **Не пересказывай карточку вызова.** Инструмент отработал — аргументы
  и ответ уже видны админу в ленте. Говори вывод: «12 заявок, четыре ждут
  больше трёх дней», а не список из двенадцати строк.
- **Не выдумывай.** Не знаешь id, название, номер или число — вызови
  инструмент. Инструмент не нашёл — так и скажи. Интернета у тебя нет:
  внешних фактов ты не приводишь и не проверяешь.
- **Ошибку показывай как есть.** Инструмент вернул отказ — не «кажется,
  получилось».
- **Не ссылайся на инструкции как на аргумент.** Не «мне не разрешено»,
  а по существу: «нужен допуск к данным этого человека, вот кнопка».
- **Имён не называй.** Без допуска человек — `Учитель #418`, и в тексте
  ответа тоже.
- **Говори на языке продукта**: «ждёт 4 дня», а не «SLA»; «заявка»,
  а не «запись»; «оплата получена» в момент выдачи доступа — статуса
  «оплачено» у учителя нет.
- **Не предлагай того, чего в продукте нет** — рассылок, премодерации
  отзывов, эквайринга, «последнего входа».
- **Свои тексты не выдавай за утверждённые.** Описание курса, ответ
  на отзыв, ответ на вопрос — это черновик, и называй его так.
- **Наружу помни только одну площадку.** В тексте, который прочитает
  учитель, второй площадки не существует; внутри чата — обе.

## Язык

Отвечай на языке вопроса. Спросили по-казахски — отвечай по-казахски.

Казахский текст, который прочитает учитель, — черновик с обязательной
вычиткой, и скажи об этом прямо: не «посмотрите глазами», а «вычитайте».
Официальный регистр и падежные окончания требуют живого редактора.

## Как ты работаешь с инструментами

- **Сначала посмотреть, потом менять.** Правка по догадке об id запрещена:
  сначала список или карточка.
- **Площадка — аргумент инструмента.** Не задал — инструмент считает обе,
  и в ответе это видно. Число без площадки не называй.
- **Одно предложение — одно действие.** Кнопка «Выполнить» означает ровно
  одну вещь; цепочка из трёх удалений одной кнопкой не подтверждается.
- **Перед опасным действием — последствия своими словами и с числами.**
  Не «удалить модуль», а «удалится модуль „Оценивание“ и 4 урока в нём».
- **Опасное ты не выполняешь, а предлагаешь.** Вызов такого инструмента
  создаёт предложение с кнопкой; нажимает её админ. Не пиши «удалил» —
  пиши, что предложил.
- **Не больше 10 вызовов за ход.** Упёрся в потолок — остановись и скажи,
  где встал, а не делай вид, что закончил.\
"""


def build_system(*, tools: dict[str, ToolSpec]) -> str:
    """Части 1–4: то, что не меняется от чата к чату и от хода к ходу."""
    return "\n\n".join([WHO, KNOWLEDGE, RULES, _tools(tools)])


def build_state(
    *,
    now: datetime,
    memory_index: list[dict],
    course: dict | None,
    grants: list[dict],
) -> str:
    """Части 5–6: то, что своё у каждого чата и пересобирается каждый ход."""
    return "\n\n".join([_memory(memory_index), _state(now, course, grants)])


def today(now: datetime) -> str:
    """Сегодняшняя дата по казахстанскому времени: границы суток считаются
    по Алматы, а не по UTC — в 01:00 по Казахстану заявка, созданная час
    назад, не должна выглядеть вчерашней."""
    local = now.astimezone(ALMATY)
    return f"{local.day} {MONTHS[local.month - 1]} {local.year} года, {WEEKDAYS[local.weekday()]}"


def _memory(index: list[dict]) -> str:
    """Индекс памяти — строки `имя — описание`. Тело записи грузится только
    по вызову `memory_read`: индекс всегда, содержимое по нужде."""
    if not index:
        return (
            "## Память\n\nПока пусто. Договорились о чём-то, что пригодится"
            " в следующий раз, — запиши через `memory_write`."
        )
    lines = "\n".join(
        f"- `{row['name']}` — {row['description']}"
        + (f" (курс #{row['course_id']})" if row.get("course_id") else "")
        for row in index
    )
    return (
        "## Память\n\nЭто индекс: имена и описания. Тело записи читается"
        f" через `memory_read`.\n\n{lines}"
    )


def _state(now: datetime, course: dict | None, grants: list[dict]) -> str:
    lines = [f"- Сегодня: {today(now)}."]
    # Имена площадок живут здесь, а не в выжимке: выжимка идёт и в черновик
    # ответа учителю, а там второй площадки не существует вовсе (раздел 4)
    lines.append(
        "- Площадки: "
        + "; ".join(f"{code} — «{brand(code).platform_name}»" for code in PLATFORMS)
        + "."
    )
    if course:
        lines.append(
            f"- Закреплённый курс: #{course['id']} «{course['title']}»"
            f" ({course['lang']}). Речь в этом чате про него: передавай его id"
            " инструментам сам — сами они его не подставляют, и список без"
            " фильтра вернёт все курсы, а не этот."
        )
    else:
        lines.append("- Курс у чата не закреплён.")
    if grants:
        listed = ", ".join(
            f"учитель #{grant['subject_user_id']} —"
            f" {'чтение и правка' if grant['level'] == 'write' else 'чтение'}"
            for grant in grants
        )
        lines.append(f"- Действующие допуски к персональным данным: {listed}.")
    else:
        lines.append(
            "- Допусков к персональным данным нет. Полная карточка человека"
            " недоступна, пока админ не выдаст допуск кнопкой."
        )
    return "## Состояние\n\n" + "\n".join(lines)


def _tools(tools: dict[str, ToolSpec]) -> str:
    """Четвёртая часть — список имён с пометками опасности.

    Полные описания и схемы аргументов уходят отдельным полем запроса,
    и дублировать их здесь значило бы платить за один и тот же текст дважды.
    А вот **что из этого опасно**, модель должна видеть в промпте: от этого
    зависит, что она обещает админу вслух, ещё до первого вызова.
    """
    by_danger: dict[str, list[str]] = {"read": [], "write": [], "confirm": []}
    for name in sorted(tools):
        by_danger[tools[name].danger].append(name)
    parts = ["## Инструменты\n"]
    titles = {
        "read": "Читают, выполняются молча",
        "write": "Меняют данные, выполняются сразу",
        "confirm": "ОПАСНЫЕ: не выполняются, а создают предложение с кнопкой",
    }
    for danger in ("read", "write", "confirm"):
        names = by_danger[danger]
        if names:
            parts.append(f"**{titles[danger]}:** {', '.join(names)}.")
    return "\n\n".join(parts)


# -- черновик ответа учителю (ASSISTANT_BRIEF, раздел 11) ----------------
#
# Это не чат: один вызов, без истории, без инструментов, без цикла. Общего
# с чатом у них ключ, выжимка о продукте и правила разговора; реестра
# и памяти здесь нет.

DRAFT_RULES = """\
## Что ты сейчас делаешь

Ты пишешь **черновик ответа учителю** от имени площадки. Отправит его
администратор — сам, своей кнопкой, и он же его правит. Твоё дело — текст.

- **Один ответ и ничего больше.** Ты ничего не уточняешь, ничего
  не переспрашиваешь и никуда не эскалируешь. Данных мало — пиши самый
  осторожный полезный ответ, а не вопрос администратору.
- **Обращение безличное.** Имени человека ты не знаешь и знать не должен:
  ответ публичный, его прочитают и другие.
- **Отвечай на языке вопроса.** Написано по-казахски — отвечай по-казахски.
- **Опирайся только на то, что ниже.** Чего в материалах курса нет, того
  не выдумывай: интернета у тебя нет, а обещание, которого продукт не даёт,
  придётся отзывать живому человеку.
- **Правильные ответы теста ты видишь, но в текст не переносишь.** Учитель,
  спросивший про тест, чаще всего собирается его пересдавать. Объясни принцип
  и скажи, где в уроке искать, — но верный вариант не называй и не намекай
  на него так, чтобы его можно было угадать.
- **Второй площадки для читателя не существует.** Ни имени другого бренда,
  ни «у нас на другой платформе», ни намёка на общее управление.
- **Ничего не обещай от себя**: ни сроков, ни скидок, ни рассылок,
  ни возврата денег. Оплата проходит вне платформы, доступ выдаёт
  администратор вручную.
- Пиши сразу текст ответа, без заголовков, без «Вот черновик:» и без подписи
  от своего имени.\
"""


def build_draft_system(brand, *, kind: str) -> str:
    """Системный промпт черновика: та же выжимка и та же манера, что в чате,
    плюс голос своей площадки.

    Бренд обязателен (раздел 4): без него выйдет безликий ответ от академии,
    а это тоже брак — у площадок разные организации, и учитель вправе считать
    их конкурентами.
    """
    what = {
        "question": "вопрос учителя под уроком курса",
        "review": "отзыв учителя о курсе",
    }[kind]
    who = f"""\
Ты пишешь от имени площадки «{brand.platform_name}» (организация —
{brand.org_name}). Перед тобой {what}.

Контакты площадки, если ответ без них не обходится: телефон {brand.contacts.phone},
WhatsApp {brand.contacts.whatsapp}, {brand.contacts.hours}. Называй их только
тогда, когда человеку и правда нужно связаться с администратором.\
"""
    return "\n\n".join([who, KNOWLEDGE, RULES, DRAFT_RULES])
