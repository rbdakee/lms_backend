"""Маскирование персональных данных в ответах инструментов.

`CLAUDE.md`: ФИО, телефоны, школы и регионы не попадают в логи, в текст ошибок
и в аналитику. У ассистента правило жёстче — его контекст целиком уходит
в модель, поэтому **списки маскированы всегда, без исключений**
(`ASSISTANT_BRIEF`, раздел 5).

Имя человека появляется ровно в одном месте — в `teacher_card`, и только
после допуска, который админ выдал кнопкой на этого человека.
"""

from app.adapters.db.models import User

# Регион и школа — тоже персональные данные (`CLAUDE.md`), но без них список
# бесполезен: по ним админ и находит нужную строку. Компромисс тот же, что
# на экране `/teachers`, с одной разницей — имени нет.
#
# ИИН и телефон не появляются в списках ни при каких условиях: телефон
# опознаёт человека однозначно, а ИИН чувствительнее всего остального
# (`CERTIFICATES_BRIEF`, раздел 1).


def teacher_ref(user_id: int) -> str:
    """Как ассистент называет человека, пока допуска нет: `Учитель #418`.

    Один вид на все списки и на текст ответа: увидев эту строку в ленте,
    админ понимает, что имени модель не знает вовсе.
    """
    return f"Учитель #{user_id}"


def masked_teacher(user: User) -> dict:
    """Строка списка: по чему найти человека, но не кто он.

    `user_id` нужен, чтобы дальше выдать допуск и открыть карточку, —
    и он же служит подписью.
    """
    return {
        "user_id": user.id,
        "ref": teacher_ref(user.id),
        "region": user.region,
        "school": user.school,
    }

