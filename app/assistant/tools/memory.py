"""Память ассистента: четыре инструмента поверх готового сервиса.

Устройство ровно как у `MEMORY.md` в Claude Code (`ASSISTANT_BRIEF`, раздел 7):
индекс — строки «имя — описание» — стоит в системном промпте каждый ход, тело
записи грузится, только когда ассистент сам его попросил. Отсюда главное
правило файла: **`memory_list` тел не отдаёт** — это суть схемы, а не экономия
токенов.

Границы (`name` — слаг, описание до 200, тело до 4000, всего 100 записей)
и запрет персданных живут в `app/application/assistant_memory.py`. Своей копии
проверок здесь нет: вторая копия рано или поздно разойдётся с первой, а расходится
она в ту сторону, где телефон учителя всё-таки уезжает в OpenAI.

`memory_delete` помечен `write`, а не `confirm`, хотя удаляет: запись памяти —
заметка ассистента о себе, а не чужая работа (раздел 7). Удалённую он тут же
напишет заново, а вот подтверждать каждую заметку кнопкой значило бы не завести
память вовсе.

**Область записи выбирается аргументом `course_id`, а не закреплённым курсом.**
Умолчание — общая память: у общей записи цена ошибки — лишняя строка в индексе
чужого чата, а у курсовой — договорённость, которой в других чатах не видно
вовсе. Исключение одно, и оно читающее: `memory_list` без аргумента показывает
то же, что уже стоит в промпте, — общее плюс закреплённый курс.
"""

from app.adapters.db.repos import CourseRepo
from app.api import deps
from app.application.assistant_memory import MemoryService
from app.assistant.registry import Arg, ToolCtx, ToolError, tool


def memory_service(ctx: ToolCtx) -> MemoryService:
    """Тот же сервис, что стоит за `/admin/assistant/memory` и за индексом
    в промпте. Собирается у `deps`, а не рядом: экран памяти и ассистент
    обязаны видеть одни и те же записи с одними и теми же границами."""
    return deps.get_memory_service(db=ctx.db)


def course_arg(description: str) -> Arg:
    return Arg("integer", description)


@tool(
    name="memory_list",
    danger="read",
    description=(
        "Индекс памяти: имена записей и их описания — общие плюс записи"
        " закреплённого курса. Тел записей здесь нет, за телом идут"
        " в memory_read. Этот же индекс стоит в системном промпте каждый ход,"
        " так что заново его читать незачем: сюда ходят, чтобы заглянуть"
        " в память другого курса или убедиться, что запись сохранилась."
    ),
    args={
        "course_id": course_arg(
            "Курс, чью память показать рядом с общей. Не задан — закреплённый"
            " у чата курс, то есть ровно тот индекс, что уже в промпте."
        )
    },
)
def memory_list(ctx: ToolCtx, course_id: int | None = None) -> dict:
    # Умолчание от закреплённого курса — чтобы ответ инструмента совпадал
    # с индексом в промпте: два разных списка модель считает изменением
    course_id = ctx.course_id if course_id is None else course_id
    items = memory_service(ctx).list_names(course_id)
    return {"course_id": course_id, "total": len(items), "items": items}


@tool(
    name="memory_read",
    danger="read",
    description=(
        "Тело одной записи памяти по имени. Имена и описания уже видны"
        " в индексе — читать имеет смысл ту запись, чьё описание отвечает"
        " на текущий вопрос, а не все подряд. Запись курса и общая запись"
        " с одним именем — разные записи: у курса своя, и достаётся она"
        " только со своим course_id."
    ),
    args={
        "name": Arg("string", "Имя записи из индекса, например «pricing»", required=True),
        "course_id": course_arg(
            "Читать запись этого курса. Не задан — читается общая запись,"
            " даже когда у чата закреплён курс."
        ),
    },
)
def memory_read(ctx: ToolCtx, name: str, course_id: int | None = None) -> dict:
    # Имена в базе лежат слагом в нижнем регистре: «Pricing» из ответа модели
    # значит ту же запись, и отказывать по регистру было бы придиркой
    return memory_service(ctx).read(name.strip().lower(), course_id)


@tool(
    name="memory_write",
    danger="write",
    description=(
        "Завести запись памяти или переписать существующую целиком."
        " Записывают то, что пригодится в следующий раз и чего не видно"
        " из инструментов: как считается цена, о чём договорились с админом,"
        " чего в этом продукте делать не просят. Пересказ разговора, ответы"
        " инструментов и числа, которые можно спросить заново, в память"
        " не пишут. Запись про одну площадку обязана называть площадку"
        " в тексте: память общая на обе, и «цена 45 000» без p1 или p2 через"
        " месяц соврёт. Персональных данных в памяти не бывает ни при каком"
        " допуске — телефон и ИИН сервер не примет."
    ),
    args={
        "name": Arg(
            "string",
            "Имя записи: слаг латиницей, например «course-pricing». Уже занятое"
            " имя означает правку той записи, а не вторую рядом.",
            required=True,
        ),
        "description": Arg(
            "string",
            "Строка индекса — о чём запись, до 200 знаков. Её ты будешь видеть"
            " каждый ход и по ней решать, стоит ли открывать тело.",
            required=True,
        ),
        "body": Arg("string", "Тело записи, до 4000 знаков", required=True),
        "course_id": course_arg(
            "Записать в память этого курса — она подмешивается только там, где"
            " курс закреплён. Не задан — запись общая и видна во всех чатах."
        ),
    },
)
def memory_write(
    ctx: ToolCtx, name: str, description: str, body: str, course_id: int | None = None
) -> dict:
    # У course_id внешний ключ: выдуманный номер уронил бы весь ход на flush,
    # а модель прочитала бы 500 вместо внятного отказа
    if course_id is not None and CourseRepo(ctx.db).by_id(course_id) is None:
        raise ToolError("not_found", f"Курса #{course_id} нет")
    return memory_service(ctx).write(
        ctx.admin, name=name, description=description, body=body, course_id=course_id
    )


@tool(
    name="memory_delete",
    danger="write",
    description=(
        "Удалить запись памяти по имени. Удаляют то, что перестало быть"
        " правдой или больше не пригодится. Устаревшую договорённость лучше"
        " переписать через memory_write, чем удалять и заводить рядом вторую"
        " с тем же смыслом."
    ),
    args={
        "name": Arg("string", "Имя записи из индекса", required=True),
        "course_id": course_arg(
            "Удалить запись этого курса. Не задан — удаляется общая запись."
        ),
    },
)
def memory_delete(ctx: ToolCtx, name: str, course_id: int | None = None) -> dict:
    return memory_service(ctx).delete(name, course_id)
