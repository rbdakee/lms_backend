"""Инструменты ассистента по областям.

Модули отсюда импортируются сами — обходом пакета, а не списком в этом
файле. Причина механическая: инструменты пишут несколько человек сразу,
и список импортов был бы единственным местом, где они сталкиваются.
Новый файл в этой папке достаточно положить — декораторы `@tool` выполнятся
при импорте пакета.
"""

import importlib
import pkgutil

# Файлы, начинающиеся с `_` и с `test_`, обходятся стороной: положенный сюда
# по ошибке тест утащил бы в боевой процесс pytest и `tests/conftest.py`,
# а тот при импорте лезет в тестовую базу. Сервис падал бы на старте.
for _module in pkgutil.iter_modules(__path__):
    if _module.name.startswith(("_", "test_")):
        continue
    importlib.import_module(f"{__name__}.{_module.name}")
