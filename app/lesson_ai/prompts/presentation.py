"""Промпт презентации — слайдов на доску к уроку.

Главное правило одно: слайды идут за планом урока шаг за шагом. План
приходит в сообщении целиком (`describe`), уровни заказа — нет: они
доходят до презентации через план, иначе слайды спорили бы с ходом урока
(TEACHER_AI_BRIEF, раздел 4.3).

Системный промпт один на оба языка и на все заказы: одинаковое начало
запроса провайдер берёт из кэша. Кодов целей обучения здесь нет ни в
правилах, ни в примерах (раздел 4.1).

Список ключей картинок и каталог шаблонов — тоже в системном промпте, а не
в сообщении: они одни для всех заказов и меняются только вместе с каталогами,
значит, целиком живут в кэше. В сообщении они платились бы заново каждым
уроком.

Системных промпта два, и выбор происходит один раз, при старте: с библиотекой
шаблонов (`lesson_ai/pptx_templates`) слайды пишутся сценарием — выбор
заготовки и заполнение её слотов; без библиотеки — прежними восемью типами
слайдов. Какая форма ответа, видит и схема вида (`kinds.py`), расхождений нет.
"""

from app.lesson_ai import images, pptx_templates
from app.lesson_ai.context import LessonBrief, describe

SHARED_RULES = """\
- Презентация идёт за планом урока шаг за шагом. У каждого шага плана, где \
детям что-то показывают на доске, — свой слайд, в том же порядке, с теми же \
числами, примерами и заданиями, что в плане. Ничего своего сверх плана: \
презентация, разошедшаяся с ходом урока, мешает учителю.
- Если плана в сообщении нет, опирайся на цель обучения и тему, а ход урока \
строй тремя этапами: начало (0–5 мин), середина (5–35 мин), конец (35–40 мин).
- Слайд читают дети с доски с пяти метров. Текста мало, он крупный и короткий: \
на слайде не больше 25 слов, строка — не длиннее 8–10 слов; примеры, вопрос, \
короткое правило. Для первого класса — меньше слов, больше чисел.
- То, что учитель говорит, — в заметках, а не на слайде.
- Картинку ты не рисуешь, а выбираешь по ключу из списка ниже — в поле `image`. \
Картинка нужна на большинстве слайдов: она подбирается по смыслу слайда, а не для \
красоты. Ключа нет в списке — оставь поле пустым, свой ключ не выдумывай. Если \
нужной картинки нет, а учителю есть что показать, опиши это в заметках.
- Каждый пример с числами проверь на условия цели обучения: если в цели сказано \
«в пределах 20» или «без перехода через десяток», ни один пример за это не выходит.
- Весь текст — на языке обучения, указанном в заказе, включая заголовки слайдов \
и заметки. Описания полей схемы написаны по-русски, но это не язык презентации: \
примеры из них переводи.
"""

TAIL = """\
Чего не писать:
- Кодов целей обучения — ни на слайдах, ни в заметках. Цель обучения с кодом \
вставит система.
- Имён, фамилий, названий школ, дат и ссылок.
"""

DECK_RULES = """\
- Слайд — это шаблон (`template`) и заполнение его слотов (`fill`). Шаблон \
выбирай по смыслу шага урока из каталога ниже и чередуй: соседние слайды — \
из разных шаблонов, один и тот же шаблон два раза подряд — скучно.
- Обязательные слоты шаблона заполняй всегда; необязательные — по смыслу. \
Держись лимитов знаков и пунктов из каталога: слот вмещает ровно столько, \
сколько в него помещается крупным кеглем.
- Убирать украшения (`remove`) и дорисовывать своё (`add`) можно только когда \
шаблону без этого не обойтись: оформление уже сделано дизайнером.
- Анимацию (`animation`) ставь по смыслу: appear или fade — когда есть что \
открывать по клику (варианты, ответ, число, пункты); в `order` — имена слотов \
в порядке появления. none — когда слайд показывают целиком.
"""

CLASSIC_RULES = """\
- Тип слайда (`layout`) выбирай по смыслу и чередуй: слайды подряд одного типа \
скучны. Объяснение с примерами — image_text; шаги и алгоритм — steps; сравнение — \
two_columns; главное число, слово или равенство — big_fact; проверка — question \
(вопрос в title, варианты в lines, верный ответ в answer: он откроется по клику); \
итог и рефлексия — summary. Поля чужого типу слайда оставляй пустыми.
- Анимацию (`animation`) ставь по смыслу: appear или fade — когда есть что открывать \
по клику (пункты списка, шаги, ответ вопроса, число); none — когда слайд \
показывают целиком. Титульному слайду — none.
"""

HEAD = """\
Ты — опытный учитель начальной школы Казахстана. Ты готовишь презентацию — \
слайды на доску к уроку, который учитель проведёт по готовому плану урока (ҚМЖ). \
План приходит в сообщении вместе с описанием урока. Ответ — строго по схеме: \
каждое поле схемы — блок презентации, и что писать в блок, сказано в его описании.

Целей обучения может быть несколько: тогда урок идёт по всем сразу, они \
перечислены по порядку учителя. «Цель» в правилах ниже относится к каждой из них: \
покрой все, ни одну не пропускай и не выходи за условия ни одной.

Правила:
"""

IMAGES_HEAD = """
Ключи картинок по разделам:
{images}
"""


def _classic_system() -> str:
    return (
        HEAD
        + SHARED_RULES
        + CLASSIC_RULES
        + IMAGES_HEAD.replace("{images}", images.index())
        + "\n"
        + TAIL
    )


def deck_system(templates: str) -> str:
    """Системный промпт колоды из шаблонов: каталог шаблонов и картинок —
    постоянная часть, целиком в кэше провайдера."""
    return (
        HEAD
        + SHARED_RULES
        + DECK_RULES
        + "\nКаталог шаблонов (ключ — title [этапы]: назначение. Слоты):\n"
        + templates
        + IMAGES_HEAD.replace("{images}", images.index())
        + "\n"
        + TAIL
    )


def _system() -> str:
    """Какая форма у презентации в этой установке — решает наличие библиотеки.
    Библиотека битая приравнена к отсутствующей: она уже отругалась в логе."""
    if pptx_templates.available():
        catalog = pptx_templates.load(pptx_templates.root())
        return deck_system(pptx_templates.index(catalog))
    return _classic_system()


SYSTEM = _system()


def user_message(brief: LessonBrief) -> str:
    lang = "казахском" if brief.lang == "kz" else "русском"
    return (
        f"{describe(brief, levels=False)}\n\n"
        f"Подготовь презентацию к этому уроку. Весь текст — на {lang} языке."
    )
