"""Промпты вложений «Жоспара»: разбор файла и блок «Материалы учителя».

Запрос к модели здесь один — снятие выжимки с фото или PDF сразу после
загрузки (`describe_media`). Дальше файл в разговоре не участвует никогда:
в служебное сообщение каждого хода чата и в контекст генерации идёт
выжимка — `materials_block`. Так контекст хода не раздувается байтами,
а выжимка платится один раз, а не на каждой реплике.
"""

INSTRUCTION = (
    "Извлеки весь текст дословно и опиши рисунки, таблицы и задания так,"
    " чтобы по одному твоему описанию можно было подготовить урок: сохрани"
    " формулировки заданий, числа, подписи и структуру таблиц. Ничего"
    " не сокращай и не пересказывай своими словами."
)

SYSTEM = f"""\
Ты готовишь выжимку файла, приложенного учителем к чату «Жоспара» — помощника \
по подготовке материалов к уроку начальной школы. Выжимку будет читать не \
учитель, а другой помощник: он по ней подбирает цели обучения и готовит план \
урока, задания и презентацию — и будет ссылаться на файл в разговоре \
(«по странице учебника, которую вы прислали»). Отсюда требования: весь текст \
дословно, включая номера страниц, подписи, обозначения и записи от руки; \
для каждой картинки, схемы и таблицы — описание, по которому понятно, что на \
ней изображено и как она связана с текстом. Если файл — фотография тетради \
или учебника, сохрани порядок: что идёт раньше, что позже. Текста нет вовсе — \
опиши, что изображено, и скажи, что текста в файле нет. Отвечай на том языке, \
на котором текст в файле.

{INSTRUCTION}
"""

# Вид вложения словами — и для модели, и для учителя у скрепки
KIND_LABELS = {
    "image": "картинка",
    "pdf": "PDF-документ",
    "docx": "документ Word",
    "pptx": "презентация PowerPoint",
}


def materials_block(rows: list[dict], *, budget: int) -> str:
    """Блок «Материалы учителя» для изменчивой части запроса.

    `rows` — вложения чата в порядке загрузки: `kind`, `pages`, `summary`
    (у ещё разбирающихся вместо выжимки `processing: True`, у упавших —
    только `error`). Общий бюджет на все выжимки в одном ходе; не влезло —
    урезается **равномерно**: один файл не должен занять бюджет целиком
    и оставить остальные невидимыми. Блок пуст, только когда файлов нет
    вовсе, — вызывающий тогда не вставляет его вовсе.

    Системный промпт этот текст не получает: он кэшируется, и материалы
    в нём стояли бы поперёк кэша.
    """
    if not rows:
        return ""
    lines = ["Материалы учителя (приложены к этому чату, пишет сервер):"]
    ready = [row for row in rows if "summary" in row]
    # Равная доля каждому, но не больше своей выжимки: освободившееся
    # не перераспределяем — файлов немного, и точность здесь не стоит цикла
    share = max(budget // len(rows), 1) if rows else budget
    for row in rows:
        head = KIND_LABELS[row["kind"]]
        if row.get("pages"):
            head += f", {row['pages']} стр."
        summary = row.get("summary")
        if summary is not None:
            text = summary.strip() or "(текст в файле не найден)"
            if len(text) > share:
                text = text[:share] + "…"
            lines.append(f"- {head}: {text}")
        elif row.get("processing"):
            lines.append(f"- {head}: файл ещё читается — содержимого пока нет")
        else:
            lines.append(f"- {head}: прочитать не получилось")
    if ready:
        lines.append(
            "Опирайся на эти материалы и ссылайся на них («по странице учебника,"
            " которую вы прислали…»). Не выдумывай того, чего в них нет; чего"
            " в материалах не хватает — так и скажи."
        )
    return "\n".join(lines)
