# Что модель читает, упёршись в потолок вызовов за ход
CAP_MESSAGE = (
    "Вызовов за этот ход больше нет. Остановись: скажи учителю, что успел изменить,"
    " и что осталось, — он напишет следующим сообщением. Не делай вид, что закончил."
)

KIT_STATUS_LABELS = {
    "generating": "собирается",
    "ready": "готов",
    "partial": "собран не весь",
    "failed": "не собрался",
}
MATERIAL_STATUS_LABELS = {
    "queued": "ждёт очереди",
    "generating": "собирается",
    "ready": "готов",
    "failed": "не получился",
}


def state_message(kit: dict | None) -> str:
    """Комплект так, как его видит модель. `kit` — `LessonKitsService`-подобная
    форма без содержимого: статусы и параметры урока."""
    if kit is None:
        return "Комплект сейчас: его нет (заказ не привязан). Править нечего."
    lines = [
        "Комплект сейчас (пишет сервер):",
        f"- тема: {kit['topic']}; {kit['grade']} класс, язык обучения: {LANG_LABELS[kit['lang']]}",
        f"- как проводим: {ENGAGEMENT_LABELS[kit['engagement_level']]};"
        f" уровень класса: {DIFFICULTY_LABELS[kit['difficulty_level']]}",
        f"- статус комплекта: {KIT_STATUS_LABELS[kit['status']]}",
        "- материалы:",
    ]
    for material in kit["materials"]:
        lines.append(
            f"  - {material['kind']} ({KIND_LABELS[material['kind']]}):"
            f" {MATERIAL_STATUS_LABELS[material['status']]}"
        )
    return "\n".join(lines)
