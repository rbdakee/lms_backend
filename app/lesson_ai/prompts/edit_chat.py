def state_message(kit: dict | None, *, materials: list[dict], budget: int) -> str:
    """Комплект так, как его видит модель. `kit` — `LessonKitsService`-подобная
    форма без содержимого: статусы и параметры урока. `materials` — вложения
    чата (`kind`, `pages`, выжимка), текст блока собирает `materials_block`
    под общим бюджетом `budget`. Изменчивое живёт здесь, а не в `SYSTEM`:
    тот кэшируется."""
    if kit is None:
        return "Комплект сейчас: его нет (материалы к этому чату не привязаны). Править нечего."
    subject = kit.get("subject_title")
    lines = [
        "Комплект сейчас (пишет сервер):",
        (f"- предмет: {subject} ({kit['subject_code']}); " if subject else "- ")
        + f"{kit['grade']} класс, язык обучения: {LANG_LABELS[kit['lang']]}",
        f"- тема: {kit['topic']}",
        f"- как проводим: {ENGAGEMENT_LABELS[kit['engagement_level']]};"
        f" уровень класса: {DIFFICULTY_LABELS[kit['difficulty_level']]}",
        f"- статус комплекта: {KIT_STATUS_LABELS[kit['status']]}",
    ]
    objectives = kit.get("objectives") or []
    if objectives:
        lines.append("- цели урока по порядку (из программы; id — для set_objectives):")
        lines.extend(
            f"  {n}. {o['code']} — {o['text']} (id {o['id']})" for n, o in enumerate(objectives, 1)
        )
    lines.append("- материалы и их оглавление (полный текст блока — get_block):")
    lines.extend(kit_outline(kit["materials"]))
    if materials:
        lines.append("")
        lines.append(materials_block(materials, budget=budget))
    return "\n".join(lines)


def suggestions(
    events: list[dict], step_names: list[str], *, stopped_at_cap: bool, text: str
) -> list[dict] | None:
    """Кнопки быстрых ответов под сообщением помощника. Прикрепляет сервер, а не
    модель: забыть их она не может, и текст кнопки всегда тот, что назван в SYSTEM.

    - сразу после смены целей, если помощник ещё ничего не пересобрал, — два пути;
    - ход упёрся в потолок вызовов — «Продолжай».
    Язык кнопок — язык разговора (казахские буквы в реплике или ответе).
    """
    lang = 1 if KZ_LETTERS & set(text.lower()) else 0
    if stopped_at_cap:
        return [{"label": CONTINUE[lang], "text": CONTINUE[lang]}]
    last = events[-1] if events else None
    if last is None or last["type"] != "objectives_changed" or "regenerate_kit" in step_names:
        return None
    return [{"label": t[lang], "text": t[lang]} for t in (REBUILD, RELATED)]
