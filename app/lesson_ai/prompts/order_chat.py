def state_message(order: dict, *, said: dict) -> str:
    """Урок так, как его видит модель разговора. `order` — та же форма,
    что уходит на экран (`LessonChatService._order_out`); `said` — что учитель
    сам сказал про два уровня: на экране у них середина по умолчанию, а модели
    надо знать, спрашивала ли она. Изменчивое живёт здесь, а не в `SYSTEM`:
    тот кэшируется."""
    objectives = order["objectives"]
    lines = ["Урок сейчас (пишет сервер):"]
    if objectives:
        first = objectives[0]
        lines.append(
            f"- цели обучения ({EDITION_LABELS[first['lang']]}, {first['grade']} класс),"
            " по порядку учителя:"
        )
        lines += [f"  {n}. {o['code']} — {o['text']}" for n, o in enumerate(objectives, start=1)]
    else:
        lines.append("- цели обучения: не подтверждены")
    lines.append(f"- язык обучения: {LANG_LABELS.get(order['lang'], 'не назван')}")
    lines.append(f"- тема: {order['topic'] or 'не названа'}")
    engagement, difficulty = said["engagement_level"], said["difficulty_level"]
    lines.append(f"- как проводим: {ENGAGEMENT_LABELS.get(engagement, 'не спрашивали')}")
    lines.append(f"- уровень класса: {DIFFICULTY_LABELS.get(difficulty, 'не спрашивали')}")
    lines.append("- материалы: " + ", ".join(KIND_LABELS[kind] for kind in order["kinds"]))
    if len(objectives) > MANY_OBJECTIVES:
        lines.append(
            f"Целей {len(objectives)}, это больше трёх. "
            + (
                "Учитель уже подтвердил, что столько и нужно, — не переспрашивай."
                if order["many_objectives_confirmed"]
                else "Ты ещё не переспрашивал: один раз спроси, точно ли столько"
                " (урок лучше сузить); ответ «да» принимай без спора."
            )
        )
    if order["missing"]:
        missing = ", ".join(ORDER_LABELS[name] for name in order["missing"])
        lines.append(f"Не хватает: {missing}.")
    else:
        lines.append(
            "Пятеро собраны: учитель видит список материалов и кнопку «Готовить»."
            " Уровни спроси, если ещё не спрашивал."
        )
    return "\n".join(lines)


