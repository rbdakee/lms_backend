def extract_message(
    *, order: dict, said: dict, shown: list[dict], dialog: list[tuple[str, str]]
) -> str:
    """Всё, что нужно разбору, одним сообщением: заказ, показанные цели
    и конец переписки, последней — реплика учителя."""
    parts = [
        state_message(order, said=said),
        "",
        "Показанные учителю цели (номер — код — предмет — текст):",
    ]
    parts += [
        f"{item['id']} — {item['code']} — {item['subject_code']} — {item['text']}" for item in shown
    ] or ["(нет)"]
    parts += ["", "Конец переписки:"]
    parts += [f"{'Учитель' if role == 'user' else 'Помощник'}: {text}" for role, text in dialog]
    return "\n".join(parts)
