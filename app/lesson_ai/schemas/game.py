"""Игра к уроку: механика, правила, что распечатать и разрезать, как считать
очки и чем награждать (TEACHER_AI_BRIEF, раздел 4.3).

Схема нарочно шире остальных. У задач форма задана — условие и ответ,
а у игры форма и есть содержание: схема с готовыми механиками на выбор выдала
бы тысяче учителей одну и ту же игру. Поэтому здесь контейнер — название,
сюжет, механика своими словами, правила, роли, карточки, очки, награда, —
а самой механики схема не диктует: ни перечисления игр, ни их имён в описаниях.
Строительные блоки из каталога приходят данными в сообщении
(`app/lesson_ai/games/select.py`), и схема от каталога не зависит.

Что рисует сервер, а не модель: лист жетонов и грамота — в каждом файле
игры, развёртка кубика и игровые монеты — если игра их требует
(L5_games_db_design, раздел 1.4). Модель только сообщает, нужны ли они,
и пишет слова награды: нарисованный моделью кубик выйдет кривым, а заказ
картинки стоит токенов, которые ничего не дают.

Ответы игры — ключ ведущего — живут внутри файла игры (`host_key`), а не
в ключах комплекта: те собираются из заданий, контрольной и домашнего,
и игру туда без решения владельца не подмешивают (дизайн, раздел 6).

Каждое поле верхнего уровня — отдельный блок: «переделай карточки» или
«сделай правила проще» перегенерирует одно поле (раздел 4.1, правило 3).
Кодов целей обучения здесь нет ни в описаниях, ни в примерах.
"""

from typing import Literal

from pydantic import Field

from app.lesson_ai.schemas import SERVER_BLOCKS, Strict, Text

__all__ = ["SERVER_BLOCKS", "GameDraft"]


class Placement(Strict):
    """Где игра стоит в плане урока — рендер печатает этап и минуты рядом."""

    stage: Literal["stage_beginning", "stage_middle", "stage_end", "whole_lesson"] = Field(
        description=(
            "Этап урока по плану, на который встаёт игра. whole_lesson — игра идёт"
            " через весь урок, и этапы плана становятся её частями."
        )
    )
    minutes: int = Field(
        ge=3,
        le=40,
        description="Сколько минут урока занимает игра, вместе с объяснением правил и наградой.",
    )
    fit: Text = Field(
        description=(
            "Как игра встаёт в план урока: какой шаг плана она заменяет или проводит,"
            " какие задания плана в ней звучат, что было до неё и что будет после."
            " Если плана нет — как игра ведёт к цели обучения."
        )
    )


class Role(Strict):
    name: Text = Field(description="Название роли в сюжете игры.")
    who: Text = Field(
        description="Кто её играет: учитель, весь класс, каждая команда, двое по очереди."
    )
    does: Text = Field(description="Что эта роль делает во время игры.")


class Rules(Strict):
    """Правила и то, что из них следует для печати. Кубик и монеты — здесь,
    а не в подготовке: переписали правила — вместе с ними обновилось,
    печатать ли развёртку кубика и монеты."""

    steps: list[Text] = Field(
        min_length=1,
        description=(
            "Правила по шагам, в порядке игры, так, как учитель объяснит их детям"
            " вслух: с чего начинаем, как ходим, что делаем с ответом, что при ошибке,"
            " когда игра кончается. Одно действие — один шаг."
        ),
    )
    needs_die: bool = Field(
        description=(
            "true, если по правилам бросают кубик. Тогда система сама положит"
            " в файл развёртку кубика — рисовать её не нужно."
        )
    )
    coins: list[int] = Field(
        description=(
            "Номиналы игровых денег в тенге, если в игре платят или покупают;"
            " листы монет напечатает система. Пустой список — денег в игре нет."
            " Номиналы и все цены в игре — строго в условиях цели обучения."
        )
    )


class Preparation(Strict):
    """Подготовка учителя вечером накануне — честно, сколько резать."""

    cutting: Text = Field(
        description=(
            "Что распечатать и вырезать: какие листы, сколько копий, что разложить"
            " по конвертам. Сколько примерно времени это займёт."
        )
    )
    sets: Text = Field(
        description=(
            "Сколько комплектов нужно и на кого: на ученика, на пару, на ряд,"
            " на команду; если известно число детей — посчитай."
        )
    )
    room: Text = Field(
        description=(
            "Как расставить класс: остаются ли дети за партами, сдвинуть ли парты,"
            " где станции или команды, что написать или начертить на доске заранее."
        )
    )
    noise: Literal["quiet", "voiced", "loud"] = Field(
        description=(
            "Сколько шума: quiet — тихо, шёпотом; voiced — ответы вслух, хором;"
            " loud — шумно, движение по классу."
        )
    )
    props: list[Text] = Field(
        description=(
            "Что понадобится сверх распечатанного — только то, что есть в любом"
            " классе: ножницы, конверты, пуговицы вместо фишек, мел, скотч."
            " Пустой список, если ничего."
        )
    )


class Printable(Strict):
    """Один лист или набор карточек. Рендер печатает `cells` таблицей
    в `columns` столбцов, рамки таблицы — линии реза."""

    title: Text = Field(description="Название листа или набора, как оно напечатано над таблицей.")
    instructions: Text = Field(description="Учителю: что с этим делать на уроке и кому раздать.")
    copies: Text = Field(description="Сколько распечатать: например, одна на каждую команду.")
    cut: Literal["grid", "none"] = Field(
        description=(
            "grid — разрезать по линиям на отдельные карточки;"
            " none — лист целиком: игровое поле, бланк команды, таблица очков."
        )
    )
    columns: Literal[1, 2, 3, 4] = Field(
        description=(
            "Сколько карточек или клеток в строке таблицы. Чем меньше столбцов,"
            " тем крупнее карточка: для первоклассников и карточек с задачей"
            " словами — 1–2, для коротких примеров и чисел — 3–4."
        )
    )
    cells: list[Text] = Field(
        min_length=1,
        description=(
            "Само содержимое — каждая строка списка это одна карточка или клетка"
            " поля, по порядку, слева направо и сверху вниз. Пиши сами примеры,"
            " числа, вопросы, слова — не «карточка с примером», а «43 + 25»."
            " Перенос строки внутри карточки — символ новой строки. Каждое число,"
            " которое называют, ищут или проверяют, должно сходиться с остальными"
            " карточками и с ключом ведущего."
        ),
    )


class Reward(Strict):
    """Слова награды. Сами жетоны и грамоту рисует система."""

    token_label: Text = Field(
        description="Надпись на жетоне: одно-два слова или число очков, крупно."
    )
    tokens_for: Text = Field(
        description="За что выдаётся жетон по ходу игры и сколько жетонов за что."
    )
    diploma_text: Text = Field(
        description=(
            "Формулировка на грамоте победителю — за что награждается, одной строкой,"
            " в падеже, который встаёт после имени победителя. Без имён."
        )
    )


class Differentiation(Strict):
    support: Text = Field(
        description=(
            "Как поддержать тех, кому трудно, внутри игры: подсказка, опора,"
            " роль полегче, карточка попроще — снаружи она такая же, как у всех."
        )
    )
    challenge: Text = Field(
        description=(
            "Что дать тем, кто справился быстро, внутри игры: карточка сложнее,"
            " роль проверяющего, задание со звёздочкой — в условиях цели обучения."
        )
    )


class KeyItem(Strict):
    item: Text = Field(
        description="Что проверяет ведущий: карточка, клетка, вопрос станции — так, чтобы её найти."
    )
    answer: Text = Field(description="Верный ответ. Проверь его дважды: по нему судят игру.")


class GameDraft(Strict):
    """Ответ модели по игре. Порядок полей — порядок документа."""

    title: Text = Field(
        description="Название игры для детей — короткое, по сюжету урока, без слова «игра»."
    )
    story: Text = Field(
        description=(
            "Сюжет: зачем детям играть — кто герой, что случилось, что нужно"
            " сделать. Два-четыре предложения так, как учитель скажет их классу."
        )
    )
    placement: Placement = Field(description="Место игры в плане урока.")
    mechanic: Text = Field(
        description=(
            "Как устроена игра, своими словами: что дети делают с карточками или полем,"
            " где в этом ходе задания по цели обучения, чем игра кончается."
            " Три-пять предложений для учителя."
        )
    )
    roles: list[Role] = Field(
        min_length=1,
        description="Роли в игре, включая роль учителя.",
    )
    rules: Rules = Field(description="Правила игры по шагам и что для них нужно напечатать.")
    preparation: Preparation = Field(description="Подготовка учителя к игре.")
    printables: list[Printable] = Field(
        min_length=1,
        description=(
            "Всё, что печатается и режется, — с полным содержимым каждой карточки"
            " и клетки. Жетоны, грамоту, кубик и монеты сюда не включай: их кладёт"
            " система."
        ),
    )
    scoring: Text = Field(
        description=(
            "Как считать очки: за что сколько, где их отмечать (доска, бланк команды),"
            " как определить победителя и что при ничьей."
        )
    )
    reward: Reward = Field(description="Чем награждать.")
    differentiation: Differentiation = Field(description="Дифференциация внутри игры.")
    host_key: list[KeyItem] = Field(
        min_length=1,
        description=(
            "Ключ для ведущего: ответ к каждой карточке, клетке и вопросу, которые"
            " в игре проверяются, — чтобы учитель судил, не решая сам."
        ),
    )
