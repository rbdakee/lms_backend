"""Задания на урок: карточки и раздатка по уровням (TEACHER_AI_BRIEF, раздел 4).

Геймификация по брифу — прежде всего про задания (раздел 4.3), поэтому игровая
подача здесь не приписка к листу, а свой блок, и каждая карточка несёт свою
игровую инструкцию. Как именно — решают два уровня заказа, их модель читает
в сообщении: `engagement_level` задаёт подачу, `difficulty_level` — высоту
всех трёх уровней карточек сразу.

Дифференциация внутри класса — три блока карточек, а не поле уровня
у карточки: «перепиши карточки для сильных» перегенерирует один блок и не
трогает остальные (раздел 4.1, правило 3). Буквы А, В, С на листе — привычная
школе запись уровней, ребёнку она не говорит «ты слабый».

Каждое задание — `Task` с ответом внутри карточки-группы: из них сервер
собирает ключи (раздел 4.2). Кода цели обучения нет ни в одном поле и ни
в одном описании — цель с кодом подставляет сервер (`SERVER_BLOCKS`).
"""

from pydantic import Field

from app.lesson_ai.schemas import SERVER_BLOCKS, Strict, Task, TaskGroup, Text

__all__ = ["SERVER_BLOCKS", "Card", "TasksDraft"]


class Card(TaskGroup):
    """Карточка — ячейка листа, которую учитель вырезает и раздаёт.

    Ответов на листе нет: заголовок и задания карточки печатаются, ответы
    уходят в отдельный файл ключей.
    """

    title: Text = Field(
        description=(
            "Заголовок карточки, как его увидит ребёнок: короткий и игровой по подаче урока —"
            " «Найди пару», «Раунд 2», «Станция „Мост“». Без слов «слабый» и «сильный»."
        )
    )
    plan_step: Text = Field(
        description=(
            "К какому шагу плана урока относится карточка: этап и шаг своими словами,"
            " как в плане, — например «Середина урока, шаг 3: самостоятельная работа»."
            " Если плана нет — этап урока и что в этот момент делает класс."
        )
    )
    instruction: Text = Field(
        description=(
            "Что сделать ребёнку, одним-двумя предложениями, вместе с игровым ходом:"
            " как ответы складываются в слово, в цвет, в очки команды или открывают"
            " следующую станцию. Если ответы расшифровывают слово — здесь же таблица"
            " «число — буква», и каждая буква соответствует ответу ровно одного задания."
        )
    )
    tasks: list[Task] = Field(
        min_length=1,
        description=(
            "Задания карточки по порядку, три-шесть штук. Каждое — с числами и с верным"
            " ответом; все числа строго в условиях цели обучения."
        ),
    )


class TasksDraft(Strict):
    """Ответ модели по заданиям на урок. Порядок полей — порядок документа."""

    intro: Text = Field(
        description=(
            "Подача заданий детям — два-четыре предложения, которые учитель прочтёт"
            " вслух перед раздачей. При спокойном уроке — тихая игра за партами;"
            " при соревновании — кто соревнуется и за что; при уроке-игре — сюжет,"
            " в котором карточки становятся станциями или этапами. Сюжет тот же,"
            " что в плане урока."
        )
    )
    game_rules: list[Text] = Field(
        min_length=1,
        description=(
            "Игровая часть по пунктам, для учителя: как ответы превращаются в игру"
            " (какое слово должно сложиться, какой цвет у какого ответа, сколько очков"
            " за верное задание и за скорость, в каком порядке идут станции), чем"
            " награждается итог. Спокойный урок — без беготни и шума."
        ),
    )
    cards_support: list[Card] = Field(
        min_length=1,
        description=(
            "Карточки уровня А — для тех, кому трудно: то же умение мелкими шагами,"
            " с опорой (образец решения первым заданием, подсказка разрядами)."
            " Одна-две карточки."
        ),
    )
    cards_core: list[Card] = Field(
        min_length=1,
        description=(
            "Карточки уровня В — для большинства класса: задания ровно те, что в плане"
            " в середине урока, с теми же числами и формой. Две-четыре карточки,"
            " каждая привязана к своему шагу плана."
        ),
    )
    cards_challenge: list[Card] = Field(
        min_length=1,
        description=(
            "Карточки уровня С — для тех, кто справился быстро: усложнение числом"
            " шагов или формой задания (пропущенное число, цепочка, задача в два"
            " действия, «найди ошибку»), а не выходом за условия цели. Одна-две карточки."
        ),
    )
    teacher_notes: list[Text] = Field(
        min_length=1,
        description=(
            "Указания учителю по пунктам: сколько экземпляров каждой карточки"
            " распечатать на класс, кому и в какой момент урока какую раздать,"
            " как быстро проверить (по ключам, взаимопроверка в парах)."
        ),
    )
