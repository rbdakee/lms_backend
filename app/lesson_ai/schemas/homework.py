"""Домашнее задание — лист, который ребёнок 1–4 класса делает дома сам.

Домашнее продолжает ровно тот урок, что в плане: тот же круг задач и те же
числа (TEACHER_AI_BRIEF, раздел 4.2). Поэтому схема не спрашивает «про что
задание» — это знает план, — а спрашивает, как разложить его на обязательную
часть и часть по желанию: дифференциация на дому держится на том, что
обязательное по силам каждому без помощи взрослого.

Игровая подача — отдельный блок, а не пометка в задачах: расшифровка слова
или табличка рекорда печатается на листе рядом с задачами, и учитель
переписывает её, не трогая сами задачи (раздел 4.1, правило 3).

Каждая задача — `Task` в группе (`TaskGroup`): ответ пишется в тот же момент,
что и задача, и из него сервер собирает ключи (раздел 4.2). Кодов целей обучения нет ни
в полях, ни в описаниях — цель с кодом подставляет сервер (`SERVER_BLOCKS`).
"""

from pydantic import Field

from app.lesson_ai.schemas import SERVER_BLOCKS, Strict, TaskGroup, Text

__all__ = ["SERVER_BLOCKS", "HomeworkDraft"]


class HomeworkDraft(Strict):
    """Ответ модели по домашнему заданию. Порядок полей — порядок листа."""

    minutes: int = Field(
        ge=10,
        le=20,
        description=(
            "Сколько минут займёт обязательная часть у ребёнка этого класса, целым"
            " числом от 10 до 20. Печатается на листе, чтобы родители видели меру."
        ),
    )
    intro: Text = Field(
        description=(
            "Обращение к ученику, одно-три коротких предложения: что сделать и как"
            " в это играть. Тон — под то, как проводили урок: тихая игра, вызов"
            " или продолжение сюжета урока. Простые слова, по силам прочесть"
            " самому ребёнку этого класса."
        )
    )
    play_legend: list[Text] = Field(
        description=(
            "Игровая подсказка, которая печатается на листе рамкой, — строками."
            " Для расшифровки слова — «число — буква», вперемешку с лишними числами;"
            " для «найди пару» — что с чем соединять; для вызова — строки таблички"
            " рекорда («Попытка 1: ... верных примеров»); для сюжета — задание героя."
            " Решений здесь нет: числа расшифровки не подписаны номерами заданий."
            " Пустой список, если игра держится на одном обращении."
        )
    )
    required: TaskGroup = Field(
        description=(
            "Обязательная часть — для всех. Заголовок вроде «Обязательно». Три-пять"
            " заданий того же вида и в том же круге чисел, что решали на уроке по плану,"
            " но не копии примеров урока; каждое ребёнок делает сам, без объяснения"
            " взрослого."
        )
    )
    optional: TaskGroup = Field(
        description=(
            "Часть по желанию — для тех, кому было легко. Заголовок вроде «По желанию»."
            " Одно-два задания на шаг сложнее обязательных: больше действий, задача"
            " в два действия, найди ошибку, составь свой пример. Числа — в тех же"
            " условиях цели, что и у обязательных."
        )
    )
    parent_note: Text = Field(
        description=(
            "Памятка родителям, два-три предложения: что сегодня учили на уроке"
            " и как помочь, не решая за ребёнка, — например, попросить проговорить"
            " решение вслух. Без оценок ребёнка и без ответов."
        )
    )
