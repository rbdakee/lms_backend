"""Проверочная работа — лист формативного оценивания с дескрипторами.

Форма та, что принята в школах Казахстана: без отметок, по критериям
оценивания, у каждого задания — уровень мыслительных навыков, дескрипторы
и баллы («Критерий оценивания — Уровень мыслительных навыков — Задание —
Дескриптор — Балл»). Критерии берутся из плана урока, а не сочиняются заново:
завуч сверяет их с ҚМЖ, и два разных списка критериев на один урок
не пройдут (TEACHER_AI_BRIEF, раздел 4.2).

Вариантов два, и это решение, а не подстраховка: за партой сидят двое,
и одинаковый лист у соседа превращает проверку в списывание. Второй вариант
параллельный — те же задания по порядку с другими числами, — поэтому критерии,
дескрипторы и баллы пишутся один раз, у первого варианта, и одна таблица
для учителя годится на оба. Повтори их модель во втором варианте — два
описания одной таблицы разошлись бы с первой правки.

Каждая задача — наследник `Task` в группе: ответ пишется вместе с заданием,
из него сервер собирает ключи (раздел 4.2). Кодов целей обучения нет ни
в полях, ни в описаниях — цель с кодом подставляет сервер (`SERVER_BLOCKS`).
"""

from typing import Literal

from pydantic import Field

from app.lesson_ai.schemas import SERVER_BLOCKS, Strict, Task, TaskGroup, Text

__all__ = ["SERVER_BLOCKS", "AssessmentDraft", "AssessedTask", "Descriptor"]

# Уровни мыслительных навыков формативного оценивания. Слаг, а не подпись:
# подпись на языке документа ставит выгрузка в Word
ThinkingLevel = Literal["knowledge", "application", "higher_order"]


class Descriptor(Strict):
    """Строка дескриптора: одно наблюдаемое действие ученика и его балл."""

    text: Text = Field(
        description=(
            "Что делает ученик, если справился: одно наблюдаемое действие с глагола,"
            " без слова «ученик» в начале — «находит сумму двузначного и однозначного"
            " числа», «записывает ответ задачи». Общими словами, без чисел задания:"
            " дескриптор годится для обоих вариантов."
        )
    )
    points: int = Field(ge=1, le=2, description="Балл за это действие: 1 или 2.")


class AssessedTask(Task):
    """Задание проверочной: условие и ответ, как у любой задачи, плюс строка
    таблицы критериев для учителя."""

    criterion: Text = Field(
        description=(
            "Критерий оценивания, который проверяет это задание, — дословно один из"
            " критериев оценивания плана урока. Нет плана — критерий по цели обучения."
        )
    )
    thinking_level: ThinkingLevel = Field(
        description=(
            "Уровень мыслительных навыков: knowledge — знание и понимание (вспомнить,"
            " назвать, вычислить по образцу); application — применение (решить пример"
            " или задачу, выбрать действие); higher_order — навыки высокого порядка"
            " (найти ошибку, сравнить способы, составить свой пример, объяснить)."
        )
    )
    descriptors: list[Descriptor] = Field(
        min_length=1,
        description="Дескрипторы задания — один-три, по наблюдаемому действию на строку.",
    )


class AssessmentVariant(TaskGroup):
    title: Text = Field(description="Заголовок варианта, как он напечатан на листе: «Вариант 1».")
    tasks: list[AssessedTask] = Field(min_length=1, description="Задания варианта по порядку.")


class AssessmentDraft(Strict):
    """Ответ модели по проверочной работе. Порядок полей — порядок листа."""

    instructions: Text = Field(
        description=(
            "Обращение к ученику, одно-два коротких предложения: что сделать и что"
            " выполнять самостоятельно. Если урок шёл игрой или соревнованием —"
            " лёгкая игровая рамка в одну фразу, но проверка остаётся проверкой."
        )
    )
    variant_1: AssessmentVariant = Field(
        description=(
            "Первый вариант: три-пять заданий, каждое проверяет цель обучения и один"
            " из критериев оценивания плана. Задания идут от знания и понимания"
            " к применению; навыки высокого порядка — одно задание в конце."
            " Здесь же у каждого задания критерий, уровень, дескрипторы и баллы."
        )
    )
    variant_2: TaskGroup = Field(
        description=(
            "Второй вариант, параллельный первому: заголовок «Вариант 2», столько же"
            " заданий в том же порядке, каждое — того же вида и той же трудности,"
            " что задание с тем же номером в первом варианте, но с другими числами."
            " Критерии, дескрипторы и баллы у него те же, что у первого, и здесь"
            " не повторяются."
        )
    )
    self_assessment: list[Text] = Field(
        min_length=1,
        description=(
            "Самооценка ученика: два-три утверждения от первого лица по цели урока"
            " — «Я умею складывать двузначные числа». Ученик отмечает рядом"
            " «получилось» или «нужна помощь»."
        ),
    )
