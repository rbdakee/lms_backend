"""Форма ҚМЖ — краткосрочного плана урока, который учитель сдаёт завучу.

Форма задана брифом и не обсуждается (TEACHER_AI_BRIEF, раздел 4): раздел,
ФИО педагога, дата, класс, количество присутствующих, тема, цели обучения
с кодом, цели урока, критерии оценивания, языковые цели, привитие ценностей,
межпредметные связи, предварительные знания, ход урока тремя фазами с колонками
«педагог — ученики — ресурсы», дифференциация, оценивание, здоровье и ТБ,
рефлексия.

Здесь — только то, что пишет модель. Остальное форма берёт не у неё:

- раздел и цели обучения с кодом подставляет сервер из справочника
  (`SERVER_BLOCKS`), и поля кода у модели нет ни в одном блоке — сочинять
  нечего (раздел 4.1, правило 2);
- ФИО педагога, дата, класс, количество присутствующих и тема — поля
  комплекта и учителя, их подставит выгрузка в Word (сессия L4): ФИО
  в содержимое материала не входит, иначе уехало бы в банк готовых
  материалов, где материал обязан быть обезличенным.

Каждое поле верхнего уровня — отдельный блок: «перепиши середину урока»
перегенерирует одно поле (раздел 4.1, правило 3). Поэтому ход урока — три поля,
а не одно.

Описания полей уходят модели в составе схемы: это и есть инструкция к блоку.
Кодов целей обучения в них нет и быть не должно — ни в примерах, ни в тексте.
"""

from pydantic import BaseModel, ConfigDict, Field

from app.lesson_ai.schemas import Text

# Блоки, которые кладёт сервер, — впереди блоков модели, в порядке формы.
SERVER_BLOCKS = ("section", "learning_objectives")

# Этапы урока и их время заданы формой ҚМЖ, модели их не выбирать.
# Выгрузка в Word (L4) печатает время рядом с этапом отсюда.
STAGE_MINUTES = {
    "stage_beginning": (0, 5),
    "stage_middle": (5, 35),
    "stage_end": (35, 40),
}


class _Strict(BaseModel):
    # Лишнее поле в ответе — ответ не по форме: так модель не может
    # дописать от себя ни код цели, ни ещё один блок
    model_config = ConfigDict(extra="forbid")


class LessonStep(_Strict):
    """Одна строка таблицы хода урока."""

    teacher: Text = Field(
        description=(
            "Действия педагога: что именно учитель говорит и делает. Конкретно — какие"
            " вопросы задаёт, какое задание даёт и с какими числами, на каком примере"
            " объясняет. Не «учитель объясняет тему», а что и как."
        )
    )
    students: Text = Field(description="Действия учеников в этот момент урока.")
    resources: list[Text] = Field(
        description=(
            "Ресурсы для этого шага: учебник, тетрадь, карточки, счётные палочки,"
            " слайд презентации. Пустой список, если ничего не нужно."
        )
    )


class LanguageGoals(_Strict):
    vocabulary: list[Text] = Field(
        min_length=1, description="Предметная лексика и терминология урока — отдельными словами."
    )
    phrases: list[Text] = Field(
        min_length=1,
        description=(
            "Полезные выражения для диалога и письма: как ученик проговаривает"
            " своё решение и отвечает на вопрос учителя."
        ),
    )


class LessonPlanDraft(_Strict):
    """Ответ модели по ҚМЖ. Порядок полей — порядок формы."""

    lesson_goals: list[Text] = Field(
        min_length=1,
        description=(
            "Цели урока: что ученики смогут сделать к концу этого урока. Две-четыре"
            " цели, наблюдаемыми действиями, строго в рамках цели обучения."
        ),
    )
    assessment_criteria: list[Text] = Field(
        min_length=1,
        description="Критерии оценивания: по каким действиям ученика видно, что цель достигнута.",
    )
    language_goals: LanguageGoals = Field(description="Языковые цели урока.")
    values: Text = Field(
        description=(
            "Привитие ценностей: какие ценности воспитывает урок и через какое"
            " действие детей на уроке."
        )
    )
    cross_curricular_links: Text = Field(
        description="Межпредметные связи: с какими предметами связан урок и в чём именно."
    )
    prior_knowledge: Text = Field(
        description="Предварительные знания: что ученики уже умеют к этому уроку."
    )
    stage_beginning: list[LessonStep] = Field(
        min_length=1,
        description=(
            "Начало урока, 0–5 минут: организационный момент, настрой, актуализация"
            " знаний, выход на тему и цель урока."
        ),
    )
    stage_middle: list[LessonStep] = Field(
        min_length=1,
        description=(
            "Середина урока, 5–35 минут: три-пять шагов — объяснение нового на примере,"
            " работа в парах или группах, самостоятельная работа, физминутка."
            " Задания конкретные, с числами."
        ),
    )
    stage_end: list[LessonStep] = Field(
        min_length=1,
        description=(
            "Конец урока, 35–40 минут: подведение итогов, рефлексия учеников,"
            " домашнее задание."
        ),
    )
    differentiation: Text = Field(
        description=(
            "Дифференциация: как поддержать тех, кому трудно, и что дать тем,"
            " кто справился быстро."
        )
    )
    assessment: Text = Field(
        description=(
            "Оценивание: как учитель проверит понимание по ходу урока — формативное"
            " оценивание, без отметок."
        )
    )
    health_and_safety: Text = Field(
        description="Здоровье и соблюдение техники безопасности на этом уроке."
    )
    reflection: list[Text] = Field(
        min_length=1,
        description="Рефлексия по уроку: вопросы, которые учитель задаст себе после урока.",
    )
