"""Презентация к уроку — слайды на доску (TEACHER_AI_BRIEF, раздел 4).

Презентация идёт за планом урока шаг за шагом: презентация, разошедшаяся
с ходом урока, хуже отсутствующей (раздел 4.2). Поэтому слайды разложены
по тем же трём этапам, что ход урока в ҚМЖ, — три блока, и «перепиши слайды
середины» переписывает один, как «перепиши середину урока» в плане.

Картинок модель не рисует: у слайда есть поле «что показать», оно уходит
в заметки докладчика, и учитель вставляет свою картинку. Сгенерированная
картинка с неверным числом палочек хуже пустого места.

Титульный слайд собирает сервер из комплекта: тема и класс. Цель обучения
с кодом — блок сервера, модели его не дают (раздел 4.1, правило 2); в файле
она стоит в заметках титульного слайда — для учителя, не для детей.
"""

from pydantic import Field

from app.lesson_ai.schemas import SERVER_BLOCKS, Strict, Text

__all__ = ["SERVER_BLOCKS", "PresentationDraft", "Slide"]


class Slide(Strict):
    title: Text = Field(
        description=(
            "Заголовок слайда — коротко, крупно, для детей: «Вспомним», «Реши пример»,"
            " «Проверь себя»."
        )
    )
    lines: list[Text] = Field(
        description=(
            "Текст на слайде — то, что дети видят на доске: примеры с числами, вопрос,"
            " короткое правило. Две-пять коротких строк; для первого класса — меньше"
            " слов, больше чисел. Ответы к заданию на этом же слайде не писать — для них"
            " отдельный слайд «Проверь себя», если он нужен по ходу урока."
        )
    )
    visual: Text = Field(
        description=(
            "Что показать на слайде картинкой: предметы, схема, числовой луч —"
            " конкретно и с количествами. Картинку вставит учитель."
        )
    )
    notes: Text = Field(
        description=(
            "Заметки для учителя: к какому шагу плана урока слайд, что учитель говорит"
            " и спрашивает, когда переключает на следующий."
        )
    )


class PresentationDraft(Strict):
    """Ответ модели по презентации. Порядок полей — порядок показа."""

    goals: list[Text] = Field(
        min_length=1,
        description=(
            "Слайд «Сегодня на уроке»: цели урока из плана словами ребёнка —"
            " «научимся…», «узнаем…». Две-три строки."
        ),
    )
    slides_beginning: list[Slide] = Field(
        min_length=1,
        description=(
            "Слайды начала урока, 0–5 минут: настрой, разминка, выход на тему —"
            " ровно то, что в начале урока по плану. Один-два слайда."
        ),
    )
    slides_middle: list[Slide] = Field(
        min_length=1,
        description=(
            "Слайды середины урока, 5–35 минут: по слайду на каждый шаг середины урока"
            " в плане, в том же порядке, с теми же числами и заданиями; объяснение"
            " нового — на примере, физминутка — если она есть в плане."
        ),
    )
    slides_end: list[Slide] = Field(
        min_length=1,
        description=(
            "Слайды конца урока, 35–40 минут: итог, рефлексия, домашнее задание —"
            " как в конце урока по плану. Один-два слайда."
        ),
    )
