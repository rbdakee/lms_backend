"""Презентация к уроку — слайды на доску (TEACHER_AI_BRIEF, раздел 4).

Презентация идёт за планом урока шаг за шагом: презентация, разошедшаяся
с ходом урока, хуже отсутствующей (раздел 4.2). Поэтому слайды разложены
по тем же трём этапам, что ход урока в ҚМЖ, — три блока, и «перепиши слайды
середины» переписывает один, как «перепиши середину урока» в плане.

Слайд — это тип (`layout`) и его поля. Один плоский класс на все восемь
типов, а не восемь классов под `oneOf`: строгий режим провайдера плохо
переносит объединения, а правка из чата заменяет слайд целиком, и ей проще
одна форма. Поле, чужое типу слайда, остаётся пустым; какое чьё — сказано в
его описании, по описаниям же помощник в режиме правки знает, что и как менять.

Картинок модель не рисует: она выбирает ключ из каталога готовых изображений
(`app/lesson_ai/images`). Сгенерированная картинка с неверным числом палочек
хуже пустого места. Ключ, которого в каталоге нет, не ошибка ответа: слайд
соберётся без картинки (`images.lookup`).

Слайды, сохранённые до появления типов, полей `layout`, `image`, `animation`
не имеют. Всё новое — с умолчаниями, так что старый комплект проходит ту же
проверку при правке и собирается как раньше (тип `image_text`).

Титульный слайд собирает сервер из комплекта: тема и класс. Цель обучения
с кодом — блок сервера, модели его не дают (раздел 4.1, правило 2); в файле
она стоит в заметках титульного слайда — для учителя, не для детей.
"""

from typing import Literal

from pydantic import Field, field_validator, model_validator

from app.lesson_ai.images import known_or_empty
from app.lesson_ai.schemas import SERVER_BLOCKS, Strict, Text

__all__ = [
    "ANIMATIONS",
    "DEFAULT_ANIMATION",
    "LAYOUTS",
    "SERVER_BLOCKS",
    "PresentationDraft",
    "Slide",
]

Layout = Literal[
    "title", "agenda", "image_text", "two_columns", "big_fact", "question", "steps", "summary"
]
Animation = Literal["none", "appear", "fade"]
LAYOUTS: tuple[str, ...] = Layout.__args__
ANIMATIONS: tuple[str, ...] = Animation.__args__

# Анимация, когда слайд её не называет: старые слайды и правка учителя без поля
# получают разумное по типу. Титульный листают без эффектов; остальное, где есть
# что открывать по клику (пункты, ответ, число), открывается.
DEFAULT_ANIMATION: dict[str, str] = {
    "title": "none",
    "agenda": "appear",
    "image_text": "appear",
    "two_columns": "appear",
    "big_fact": "fade",
    "question": "appear",
    "steps": "appear",
    "summary": "appear",
}


class Slide(Strict):
    layout: Layout = Field(
        default="image_text",
        description=(
            "Тип слайда — как он устроен на доске. Поля ниже заполняются по типу;"
            " чужие типу поля остаются пустыми («» или []). Типы:"
            " title — титульный или заставка раздела (title + одна-две строки lines);"
            " agenda — «Сегодня на уроке» (title + 2–3 строки lines, цели словами ребёнка);"
            " image_text — картинка и короткий текст (title, lines, image);"
            " two_columns — сравнение «было / стало», «можно / нельзя»"
            " (title, left_title, lines, right_title, right_lines);"
            " big_fact — одно крупное число, слово или равенство (title, fact,"
            " подпись в lines, image);"
            " question — вопрос с вариантами, ответ открывается по клику"
            " (title — сам вопрос, lines — варианты, answer, image);"
            " steps — нумерованные шаги, алгоритм (title, lines — по шагу в строке);"
            " summary — итог, рефлексия, домашнее задание (title, lines)."
            " Смени тип — переложи текст в поля нового типа."
        ),
    )
    title: Text = Field(
        description=(
            "Заголовок слайда — коротко, крупно, для детей: «Вспомним», «Реши пример»,"
            " «Проверь себя». У слайда-вопроса (question) здесь сам вопрос."
        )
    )
    lines: list[Text] = Field(
        default_factory=list,
        description=(
            "Основной текст слайда крупно — то, что дети видят на доске. По типу:"
            " image_text — две-четыре короткие строки: примеры с числами, правило;"
            " agenda — цели урока; two_columns — левая колонка; big_fact — подпись под"
            " числом (0–1 строка); question — варианты ответа (2–4 строки, без букв и"
            " номеров: их ставит шаблон), для открытого вопроса пусто; steps — по шагу"
            " в строке, 3–5 шагов; summary — 2–4 пункта итога; title — подзаголовок."
            " Строка — не длиннее 8–10 слов. Для первого класса — меньше слов, больше"
            " чисел. Ответы к заданию на этом же слайде не писать (кроме поля answer"
            " у question): для них отдельный слайд «Проверь себя»."
        ),
    )
    left_title: str = Field(
        default="",
        description="Только two_columns: заголовок левой колонки, 1–3 слова. Иначе пусто.",
    )
    right_title: str = Field(
        default="",
        description="Только two_columns: заголовок правой колонки, 1–3 слова. Иначе пусто.",
    )
    right_lines: list[Text] = Field(
        default_factory=list,
        description=(
            "Только two_columns: правая колонка, две-четыре короткие строки"
            " (левая — в lines). У остальных типов пусто."
        ),
    )
    fact: str = Field(
        default="",
        description=(
            "Только big_fact: то, что показывается огромным кеглем, — число, слово или"
            " равенство, не длиннее 12 символов: «7», «3 + 4 = 7», «в 2 раза». У"
            " остальных типов пусто."
        ),
    )
    answer: str = Field(
        default="",
        description=(
            "Только question: верный ответ, коротко. Он открывается на слайде по клику"
            " учителя, поэтому в заголовке и вариантах его быть не должно. У остальных"
            " типов пусто."
        ),
    )
    image: str = Field(
        default="",
        description=(
            "Ключ картинки из каталога готовых изображений (список ключей — в инструкции"
            " составителя; помощнику в чате — инструмент find_image). Картинка стоит"
            " рядом с текстом и подбирается по смыслу слайда: яблоко к счёту яблок, облако"
            " к погоде. Пусто — слайд без картинки. Ключа нет в каталоге — слайд"
            " соберётся без картинки, поэтому свой ключ не выдумывать."
        ),
    )
    animation: Animation = Field(
        default="appear",
        description=(
            "Анимация слайда в PowerPoint: none — всё видно сразу; appear — строки"
            " списка (шаги, пункты) появляются по клику одна за другой, у question —"
            " по клику открывается ответ, у big_fact — число; fade — то же, но плавно."
            " Титульному слайду — none; слайдам с пунктами, вопросом, шагами — appear"
            " или fade. Слайд без элементов, которые можно открывать, остаётся без анимации."
        ),
    )
    visual: str = Field(
        default="",
        description=(
            "Только если в каталоге нет нужной картинки: что учителю показать или"
            " нарисовать к слайду — предметы, схема, числовой луч, конкретно и с"
            " количествами. Уходит в заметки докладчика, на слайде не видно. Иначе пусто."
        ),
    )
    notes: Text = Field(
        description=(
            "Заметки для учителя: к какому шагу плана урока слайд, что учитель говорит"
            " и спрашивает, когда переключает на следующий. На слайде не видны."
        )
    )

    @field_validator("image")
    @classmethod
    def _known_image(cls, value: str) -> str:
        return known_or_empty(value)

    @model_validator(mode="before")
    @classmethod
    def _old_slide(cls, data):
        """Слайд без `animation` — старый или правленный руками: умолчание берётся
        по его типу, а не одно на всех (титульному эффекты не нужны)."""
        if isinstance(data, dict) and "animation" not in data:
            layout = data.get("layout") or "image_text"
            data = {**data, "animation": DEFAULT_ANIMATION.get(layout, "appear")}
        return data


class PresentationDraft(Strict):
    """Ответ модели по презентации. Порядок полей — порядок показа."""

    goals: list[Text] = Field(
        min_length=1,
        description=(
            "Слайд «Сегодня на уроке» (тип agenda): цели урока из плана словами"
            " ребёнка — «научимся…», «узнаем…». Две-три строки."
        ),
    )
    slides_beginning: list[Slide] = Field(
        min_length=1,
        description=(
            "Слайды начала урока, 0–5 минут: настрой, разминка, выход на тему —"
            " ровно то, что в начале урока по плану. Один-два слайда."
        ),
    )
    slides_middle: list[Slide] = Field(
        min_length=1,
        description=(
            "Слайды середины урока, 5–35 минут: по слайду на каждый шаг середины урока"
            " в плане, в том же порядке, с теми же числами и заданиями; объяснение"
            " нового — на примере, физминутка — если она есть в плане. Типы слайдов"
            " чередуются: объяснение — image_text или steps, проверка — question,"
            " главное число — big_fact."
        ),
    )
    slides_end: list[Slide] = Field(
        min_length=1,
        description=(
            "Слайды конца урока, 35–40 минут: итог, рефлексия, домашнее задание —"
            " как в конце урока по плану (тип summary). Один-два слайда."
        ),
    )
