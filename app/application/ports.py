"""Порты — что сценариям нужно от внешнего мира. Порт описывает потребность
домена, а не API поставщика: смена провайдера SMS — это новый адаптер
и строчка в конфигурации, а не правки здесь.

Дальше сюда добавится video — по мере сессий плана.
"""

from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field
from typing import Any, Protocol


class SmsPort(Protocol):
    def send_code(self, phone: str, code: str) -> None: ...


@dataclass(frozen=True)
class NotificationCard:
    """Уведомление админам как его видит домен: заголовок, строки деталей,
    кнопка-ссылка на разбор в админке.

    Не HTML и не разметка конкретного мессенджера — то, во что это
    превращается (жирный заголовок, inline-кнопка), решает уже адаптер:
    порт описывает потребность домена, а не API Telegram.
    """

    title: str
    lines: list[str] = field(default_factory=list)
    link_text: str = ""
    link_url: str = ""


class TelegramPort(Protocol):
    """Доставка сообщений в Telegram. Оба метода при неудаче поднимают
    исключение: «сообщение не ушло» обязано отличаться от «ушло»."""

    def notify_admins(self, card: NotificationCard) -> None:
        """Уведомить всех админов одной карточкой: заявки и работы на проверку
        идут в общий бот, а не каждому персонально."""
        ...

    def send_to(self, chat_id: str, text: str) -> None:
        """Обычный текст в конкретный чат: бот отвечает туда, откуда пришла
        команда, — а это не обязательно тот чат, куда идут уведомления.
        Карточка здесь не нужна: подтверждение привязки и отказ по коду —
        не уведомления, а ответ в диалоге."""
        ...


class StoragePort(Protocol):
    """Приватное хранилище файлов: материалы уроков и сданные работы.

    Потребность домена ровно в трёх действиях, и ни одно из них не знает
    про диск, бакеты и подписи. Публичного адреса у объекта нет вовсе —
    наружу уходит только `key`, а байты раздаёт подписанная ссылка.
    """

    def save(self, key: str, chunks: Iterable[bytes]) -> int:
        """Записать содержимое под ключом и вернуть размер в байтах.

        Content приходит кусками: файл в 20 МБ не должен оказываться
        в памяти целиком. Исключение внутри итератора (превышен лимит,
        оборвалась загрузка) обязано не оставлять недописанный объект.
        """
        ...

    def size(self, key: str) -> int | None:
        """Размер объекта; None — объекта нет. Дешёвая проверка перед
        раздачей: сначала узнаём, что отдавать, потом открываем поток."""
        ...

    def read(self, key: str) -> Iterator[bytes]:
        """Содержимое кусками — для локальной раздачи байтов."""
        ...


# -- ИИ: чат с вызовом инструментов --------------------------------------
#
# Порт описывает потребность ассистента, а не API OpenAI: «дай ответ на эту
# переписку, вот что ты умеешь вызывать». Смена провайдера — новый адаптер
# и строчка в конфигурации, а `loop.py` не меняется вовсе.


@dataclass(frozen=True)
class AiToolCall:
    """Модель просит вызвать инструмент. `id` возвращается ей обратно вместе
    с результатом — по нему она сопоставляет ответ с вопросом."""

    id: str
    name: str
    arguments: dict[str, Any]


@dataclass(frozen=True)
class AiMessage:
    """Одно сообщение переписки как её видит ассистент.

    Роли три, и каждая заполняет своё: `user` — текст админа, `assistant` —
    текст модели и её просьбы о вызовах, `tool` — результат одного вызова
    с `tool_call_id` той просьбы.
    """

    role: str
    content: str = ""
    tool_calls: tuple[AiToolCall, ...] = ()
    tool_call_id: str = ""


@dataclass(frozen=True)
class AiReply:
    text: str
    tool_calls: tuple[AiToolCall, ...] = ()
    # Токены пишутся в ленту, чтобы счёт за месяц можно было объяснить
    # (ASSISTANT_BRIEF, раздел 9).
    tokens_in: int = 0
    tokens_out: int = 0


@dataclass(frozen=True)
class AiDelta:
    """Кусок ответа по мере генерации — то, из чего складывается стрим.

    Последним приходит событие с заполненным `reply`: ответ целиком, вместе
    с вызовами инструментов и расходом токенов. Собрать его из кусков нельзя —
    аргументы вызовов провайдер шлёт своими полями, а расход отдельным
    служебным событием в самом конце.
    """

    text: str = ""
    reply: "AiReply | None" = None


class AiPort(Protocol):
    def complete(
        self,
        *,
        system: str,
        messages: list[AiMessage],
        tools: list[dict] | None = None,
    ) -> AiReply:
        """Один запрос к модели.

        `system` отдельным аргументом, а не первым сообщением: он собирается
        заново на каждый ход и в историю чата не попадает. `tools` пустой —
        это черновик ответа: один вызов, без инструментов и без цикла
        (ASSISTANT_BRIEF, раздел 11).

        Неудача — исключение: «ответа нет» обязано отличаться от «ответ пуст».
        """
        ...

    def complete_json(
        self,
        *,
        system: str,
        messages: list[AiMessage],
        name: str,
        schema: dict,
    ) -> AiReply:
        """Один запрос, ответ на который обязан лечь в JSON-схему `schema`.

        Нужен генерации материалов «Жоспара»: модель заполняет структуру,
        а не пишет сочинение (TEACHER_AI_BRIEF, решение 7). `text` ответа —
        JSON строкой; разбирает и проверяет его вызывающий, потому что
        «ответ не по форме» — не поломка провайдера, а повод спросить ещё раз.

        Неудача провайдера — исключение, как у `complete`.
        """
        ...

    def stream(
        self,
        *,
        system: str,
        messages: list[AiMessage],
        tools: list[dict] | None = None,
    ) -> "Iterator[AiDelta]":
        """То же самое, но текст приходит кусками по мере генерации.

        Нужен ровно затем, чтобы на длинной задаче экран не молчал полминуты
        (`ASSISTANT_BRIEF`, раздел 13, фаза B3). Форма ответа та же: последнее
        событие несёт готовый `AiReply`, и цикл вызовов работает с ним так же,
        как с ответом `complete`.
        """
        ...
