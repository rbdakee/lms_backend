import logging

log = logging.getLogger("sms")


class LogSms:
    """Заглушка на время регистрации имени отправителя: пишет код в лог.

    Без неё разработка стоит — войти нельзя. Телефон в лог не попадает
    целиком (правило ПД), последних четырёх цифр хватает, чтобы понять,
    какому из тестовых номеров ушёл код.
    """

    def send_code(self, phone: str, code: str) -> None:
        log.info("SMS на ***%s: код %s", phone[-4:], code)
